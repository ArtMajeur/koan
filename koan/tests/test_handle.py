def _triage_output(verdict, questions=()):
    payload = {"verdict": verdict, "summary": "Checked app/cart.py:42.", "questions": list(questions)}
    return f"Assessment...\n\n```json\n{json.dumps(payload)}\n```"


def _plan_body(questions_text):
    return (
        "## Fix the cart total\n\n### Summary\n\nDo it.\n\n"
        f"### Open Questions\n\n{questions_text}\n\n---\n_Generated by Kōan_"
    )


def _plan_comment(questions_text, created_at):
    return {"author": BOT, "body": _plan_body(questions_text), "created_at": created_at}


class FakeGitHub:
    """In-memory stand-in for handle_github and the CI read, recording every write."""

    def __init__(self):
        self.issue = {"title": "Cart total wrong", "body": "Total is off by one.", "state": "open",
                      "author": "reporter", "node_id": "I_1", "html_url": ISSUE, "is_pr": False}
        self.comments = [{"author": "dev", "body": f"@{BOT} handle", "created_at": 1.0}]
        self.pr_comments = []
        self.pr_reviews = []
        self.authorized = {"dev", "lead"}
        self.posted = []
        self.open_pr = None
        self.pr_state = "OPEN"
        self.ci_state = "success"
        self.preview = ("pending", "")
        self.handed_off = []
        self.board_moves = []
        self.board_error = ""
        self.assigned = False
        self.fail_comments_with = None
        self.cross_repository = False
        self.files = []
        self.changed_files = None
        self.head_after_listing = None
        self.redirects = {}  # old issue URL → where GitHub now serves it
        self.pr_calls = []  # (owner, repo, number) of every PR read
        self.repo_calls = set()  # (owner, repo) of every other PR read or write
        self.linked = []  # open PRs GitHub lists as closing the issue (or the read's error)
        self.unauthorized_repos = set()  # where no one may command the bot
        self.unreadable_pulls = set()  # PR URLs GitHub no longer serves
        self.pulls = set()  # PR URLs outside the issue's repository
        self.threads = {}  # (repo, number) → comments of such a PR

    def install(self, enter):
        gh = handle_runner.gh
        for name in ("fetch_issue", "fetch_comments", "fetch_review_activity", "linked_prs",
                     "post_comment", "assign_self",
                     "find_open_pr", "pr_info", "hand_off_pr", "preview_status",
                     "merge_commit_sha", "is_team_member", "move_on_board", "is_authorized",
                     "pr_files", "pr_changed_files"):
            enter(patch.object(gh, name, getattr(self, name)))
        enter(patch.object(handle_ci, "ci_at_head", self.ci_at_head))

    def ci_at_head(self, branch, full_repo, head):
        self.repo_calls.add(tuple(full_repo.split("/")))
        return self.ci_state

    def linked_prs(self, owner, repo, number):
        if isinstance(self.linked, Exception):
            raise self.linked
        return [dict(pr) for pr in self.linked]

    def fetch_issue(self, owner, repo, number):
        pull = f"https://github.com/{owner}/{repo}/pull/{number}"
        if pull in self.pulls:
            return {**self.issue, "html_url": pull, "is_pr": True, "author": BOT, "state": "open"}
        url = f"https://github.com/{owner}/{repo}/issues/{number}"
        # With transfers in play, an issue GitHub does not redirect is itself.
        here = url if self.redirects else self.issue["html_url"]
        return {**self.issue, "html_url": self.redirects.get(url, here)}

    def fetch_comments(self, owner, repo, number):
        if self.fail_comments_with:
            raise self.fail_comments_with
        if (repo, number) in self.threads:
            return list(self.threads[(repo, number)])
        return list(self.pr_comments if number == "12" else self.comments)

    def fetch_review_activity(self, owner, repo, number):
        return list(self.pr_reviews)

    def post_comment(self, owner, repo, number, body):
        self.posted.append(body)

    def assign_self(self, owner, repo, number):
        self.assigned = True
        return True

    def find_open_pr(self, owner, repo, branch, bot):
        return self.open_pr

    def pr_info(self, owner, repo, number):
        self.pr_calls.append((owner, repo, number))
        pull = f"https://github.com/{owner}/{repo}/pull/{number}"
        if pull in self.unreadable_pulls:
            raise RuntimeError("gh: Could not resolve to a PullRequest")
        return {"state": self.pr_state, "headRefOid": HEAD, "isDraft": True,
                "url": pull if pull in self.pulls else PR,
                "headRefName": "feature/x", "isCrossRepository": self.cross_repository}

    def pr_files(self, owner, repo, number):
        self.repo_calls.add((owner, repo))
        return [dict(f) for f in self.files]

    def pr_changed_files(self, owner, repo, number):
        self.repo_calls.add((owner, repo))
        total = self.changed_files if self.changed_files is not None else len(self.files)
        return total, self.head_after_listing or HEAD

    def merge_commit_sha(self, owner, repo, number):
        self.repo_calls.add((owner, repo))
        return "merge456"

    def hand_off_pr(self, owner, repo, number, reviewer, is_draft):
        self.repo_calls.add((owner, repo))
        self.handed_off.append((number, reviewer))

    def preview_status(self, owner, repo, environment, shas):
        self.repo_calls.add((owner, repo))
        return self.preview

    def is_team_member(self, org, team, login):
        return False

    def move_on_board(self, board, node_id, column):
        self.board_moves.append(column)
        return self.board_error

    def is_authorized(self, owner, repo, login, project_name):
        return login in self.authorized and repo not in self.unauthorized_repos


