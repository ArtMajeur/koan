class TestTriage:
    def test_go_assigns_and_queues_plan(self, pipeline):
        ok, _ = pipeline.run()
        assert ok
        assert pipeline.github.assigned
        assert pipeline.record()["phase"] == "planning"
        assert f"/plan {ISSUE}" in pipeline.pending()[0]
        assert f"/handle {ISSUE} after:plan" in pipeline.pending()[1]
        assert "app/cart.py:42" in pipeline.github.posted[0]

    def test_needs_human_gates_and_pings_requester(self, pipeline):
        pipeline.set_triage(_triage_output("needs_human", ["Which currency?"]))
        pipeline.run()
        record = pipeline.record()
        assert (record["phase"], record["resume"]) == ("waiting_human", "triage")
        assert "@dev" in pipeline.github.posted[0]
        assert "Which currency?" in pipeline.github.posted[0]
        assert pipeline.pending() == []

    def test_secrets_redacted_from_posted_triage(self, pipeline):
        token = "ghp_" + "a" * 36
        output = (
            "```json\n" + json.dumps({"verdict": "needs_human", "summary": f"token {token}",
                                      "questions": [f"Is {token} yours?"]}) + "\n```"
        )
        pipeline.set_triage(output)
        pipeline.run()
        assert token not in pipeline.github.posted[0]

    def test_crashed_triage_still_pings_requester(self, pipeline):
        pipeline.set_triage(RuntimeError("idle timeout"))
        pipeline.run()
        assert pipeline.record()["phase"] == "waiting_human"
        assert "@dev" in pipeline.github.posted[0]

    def test_unparseable_triage_gates(self, pipeline):
        pipeline.set_triage("I could not decide.")
        pipeline.run()
        assert pipeline.record()["phase"] == "waiting_human"

    def test_requester_falls_back_to_issue_author(self, pipeline):
        pipeline.github.comments = []
        pipeline.set_triage(_triage_output("not_a_bug"))
        pipeline.run()
        assert "@reporter" in pipeline.github.posted[0]


