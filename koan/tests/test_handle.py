def _triage_output(verdict, questions=()):
    payload = {"verdict": verdict, "summary": "Checked app/cart.py:42.", "questions": list(questions)}
    return f"Assessment...\n\n```json\n{json.dumps(payload)}\n```"


def _plan_body(questions_text):
    return (
        "## Fix the cart total\n\n### Summary\n\nDo it.\n\n"
        f"### Open Questions\n\n{questions_text}\n\n---\n_Generated by Kōan_"
    )


def _plan_comment(questions_text, created_at):
    return {"author": BOT, "body": _plan_body(questions_text), "created_at": created_at}


