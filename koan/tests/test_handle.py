def _write_sidecar(instance_dir, lgtm, written_at, head_sha=HEAD, name="owner_repo_12.json"):
    path = Path(instance_dir) / ".review-findings" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(written_at))
    path.write_text(json.dumps({"timestamp": stamp, "head_sha": head_sha,
                                "review_summary": {"lgtm": lgtm}}))


